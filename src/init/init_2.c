#include "cub3d.h"

t_map	*init_map(char *filename)
{
	t_map	*map;

	map = malloc(sizeof(t_map));
	if (!map)
		return (NULL);
	map->lines = get_lines(filename);
	if (!map->lines)
		return (free(map), NULL);
	map->grid = NULL;
	map->height = 0;
	map->width = 0;
	map->left = 0;
	return (map);
}
